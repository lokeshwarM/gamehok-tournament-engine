package com.gamehok.tournament.enums;

/**
 * Categorizes how participants are grouped in a tournament.
 * <p>
 * SOLO: Single player competes alone (1v1, FFA)
 * DUO: Two players as a team
 * SQUAD: 3–5 players as a team
 * </p>
 */
public enum TeamType {

    SOLO,
    DUO,
    TRIO,
    SQUAD,
    CUSTOM
}
